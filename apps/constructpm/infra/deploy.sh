#!/usr/bin/env bash
# Deploy. Run on the server from apps/constructpm, after `git pull`:
#   ./infra/deploy.sh             the build of the code you just pulled
#   ./infra/deploy.sh --rollback  the build that was running before the last deploy
#   IMAGE_TAG=<sha> ./infra/deploy.sh   a specific build
#
# 1. Picks the exact images CI built for this commit (not "latest", which
#    could be a build you haven't pulled the code for). If CI hasn't finished
#    publishing them yet, it stops and says so.
# 2. Backs up the database (infra/backup.sh --db-only) before any migration
#    runs, so a bad migration can be undone with infra/restore.sh.
# 3. Applies migrations, restarts, waits for the API to report ready, and
#    records the deploy in deploys.log.
#
# Rolling back changes the code, not the database: migrations only go forward.
# If a migration itself must be undone, restore the pre-deploy backup.
set -euo pipefail
cd "$(dirname "$0")/.."
. infra/lib.sh

ROLLBACK=false
[ "${1:-}" = "--rollback" ] && ROLLBACK=true

load_env
set_profiles

# ─── Which build ─────────────────────────────────────────────────────────────
# deploys.log doesn't exist before the first deploy: `|| true`, or pipefail +
# errexit would end the script here without a word.
CURRENT="$(tail -1 deploys.log 2>/dev/null | awk '{print $2}' || true)"
if $ROLLBACK; then
  PREVIOUS="$(awk '{print $2}' deploys.log 2>/dev/null | tail -2 | head -1 || true)"
  [ -n "$PREVIOUS" ] && [ "$PREVIOUS" != "$CURRENT" ] || { echo "✗ no earlier deploy recorded in deploys.log" >&2; exit 1; }
  IMAGE_TAG="$PREVIOUS"
elif [ -z "${IMAGE_TAG:-}" ] || [ "${IMAGE_TAG}" = "latest" ]; then
  # CI builds images for commits that touch the app (or its workflow), so the
  # build for this checkout is the newest such commit.
  IMAGE_TAG="$(git -C ../.. log -1 --format=%H -- apps/constructpm .github/workflows/constructpm-ci.yml)"
fi
export IMAGE_TAG
echo "▶ deploying build ${IMAGE_TAG:0:12}${COMPOSE_PROFILES:+ (with: $COMPOSE_PROFILES)}"

# Self-heal key ownership. The API container runs as uid 1001 and bind mounts
# preserve host ownership, so keys generated by root are unreadable inside it.
if [ "$(id -u)" = "0" ] && [ -f secrets/jwt_private.pem ]; then
  chown 1001:1001 secrets/jwt_private.pem secrets/jwt_public.pem 2>/dev/null || true
fi

echo "▶ pulling images"
# Our own images must pull, or the deploy stops before touching anything.
if ! $COMPOSE pull --quiet api web migrate; then
  echo "✗ The images for ${IMAGE_TAG:0:12} aren't published yet." >&2
  echo "  Wait for GitHub Actions → ConstructPM CI → 'Build & publish images' to finish, then run this again." >&2
  exit 1
fi
# Third-party images are pinned and already on the server; refreshing them is
# best-effort so an upstream registry going away can't block a release.
$COMPOSE pull --quiet --ignore-pull-failures postgres redis caddy \
  || echo "  (some third-party images couldn't be refreshed; the copies on this server are used)"

# ─── Back up before changing the schema ──────────────────────────────────────
if [ "${SKIP_PREDEPLOY_BACKUP:-}" = "1" ]; then
  echo "▶ skipping the pre-deploy backup (SKIP_PREDEPLOY_BACKUP=1)"
elif [ -z "${BACKUP_PASSPHRASE:-}" ]; then
  echo "⚠ BACKUP_PASSPHRASE not set — no pre-deploy backup taken. Set it (see .env.production.example)." >&2
elif $COMPOSE ps --status running --services 2>/dev/null | grep -qx postgres; then
  echo "▶ backing up the database first"
  ./infra/backup.sh --db-only
fi

echo "▶ applying migrations"
# `run --rm` runs the one-shot to completion and returns its exit code, starting
# only what it depends on. A failure aborts with the old containers still serving.
$COMPOSE run --rm migrate

echo "▶ starting services"
$COMPOSE up -d --remove-orphans

# Caddy reads its settings once, and a single-file bind mount keeps showing
# the old file after `git pull` replaces it. So when the Caddyfile changed,
# recreate the container: a second or two, certificates kept in caddy_data.
if [ "$($COMPOSE exec -T caddy sha256sum /etc/caddy/Caddyfile 2>/dev/null | cut -d' ' -f1)" != "$(sha256sum Caddyfile | cut -d' ' -f1)" ]; then
  echo "▶ web server settings changed — restarting Caddy"
  $COMPOSE up -d --force-recreate --no-deps caddy
fi

echo "▶ waiting for the API to report ready"
for i in $(seq 1 30); do
  if $COMPOSE exec -T api node -e "require('http').get('http://localhost:3001/health/ready',r=>process.exit(r.statusCode===200?0:1)).on('error',()=>process.exit(1))" 2>/dev/null; then
    echo "$(date -u +%Y-%m-%dT%H:%M:%SZ) $IMAGE_TAG" >> deploys.log
    echo "✅ deployed ${IMAGE_TAG:0:12} — $($COMPOSE ps --format '{{.Service}}' | tr '\n' ' ')"
    [ -n "$CURRENT" ] && [ "$CURRENT" != "$IMAGE_TAG" ] && echo "   (previous: ${CURRENT:0:12} — './infra/deploy.sh --rollback' to go back)"
    exit 0
  fi
  sleep 2
done
echo "❌ API did not become healthy; recent logs:" >&2
$COMPOSE logs --tail 50 api >&2
[ -n "$CURRENT" ] && echo "   To go back to ${CURRENT:0:12}: ./infra/deploy.sh --rollback" >&2
exit 1
